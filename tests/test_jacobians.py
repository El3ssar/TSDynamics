"""
Jacobian correctness sweeps.

1. Every map's hand-written ``_jacobian`` is validated against central finite
   differences of ``_step`` at deterministic, well-scaled domain points.
   Stencils outside the domain or crossing discontinuities are screened by
   finite-difference convergence independently of the claimed Jacobian. Every
   remaining comparison must pass; classes can opt out explicitly via
   ``_jacobian_fd_check = False``.
2. Every ODE system that hand-defines ``_jacobian`` is cross-checked against
   the SymEngine-autogenerated Jacobian (``ContinuousSystem.jacobian``) at
   random states — any disagreement is a real bug in the hand-written matrix.
"""

from __future__ import annotations

import inspect
from types import SimpleNamespace

import numpy as np
import pytest

_N_POINTS = 8
_FD_H = 1e-6


def _map_probe_points(dim: int, n: int) -> np.ndarray:
    """Probe the unit interval and both signs without requiring a bounded orbit.

    The interior block covers interval/population maps; its negative and shifted
    copies also exercise other branches of maps defined on the real line.
    """
    interior = np.random.default_rng(20261022).uniform(0.1, 0.9, size=(n, dim))
    return np.concatenate((interior, -interior, 1.0 + interior))


def _fd_jacobian(step, x: np.ndarray, params: tuple, relative_step: float = _FD_H) -> np.ndarray:
    """Central finite-difference Jacobian of ``step`` at ``x``."""
    dim = x.shape[0]
    J = np.empty((dim, dim))
    for j in range(dim):
        h = relative_step * max(1.0, abs(x[j]))
        xp, xm = x.copy(), x.copy()
        xp[j] += h
        xm[j] -= h
        with np.errstate(over="ignore", invalid="ignore"):
            fp = np.asarray(step(xp, *params), dtype=float).ravel()
            fm = np.asarray(step(xm, *params), dtype=float).ravel()
            J[:, j] = (fp - fm) / (2.0 * h)
    return J


def _smooth_fd_jacobian(step, x: np.ndarray, params: tuple) -> np.ndarray | None:
    """Accept a finite stencil only when halving its width gives the same slope.

    This decision never reads the analytic Jacobian: a wrong matrix cannot
    remove its own failing comparison by pretending that a point is a kink.
    """
    coarse = _fd_jacobian(step, x, params)
    fine = _fd_jacobian(step, x, params, _FD_H / 2.0)
    if not (np.isfinite(coarse).all() and np.isfinite(fine).all()):
        return None
    if not np.allclose(coarse, fine, rtol=1e-4, atol=1e-6):
        return None
    return fine


def test_map_jacobian_matches_finite_differences(map_entry) -> None:
    cls = map_entry.cls
    if not getattr(cls, "_jacobian_fd_check", True):
        pytest.skip(f"{map_entry.name} opted out (_jacobian_fd_check = False)")

    sys = cls()
    params = sys.params.as_tuple()
    step, jac = type(sys)._step, type(sys)._jacobian

    points = _map_probe_points(sys.dim, _N_POINTS)
    checked = 0
    for x in points:
        J_fd = _smooth_fd_jacobian(step, x.copy(), params)
        if J_fd is None:
            continue  # invalid domain or a non-convergent difference stencil
        J_analytic = np.atleast_2d(np.asarray(jac(x.copy(), *params), dtype=float))
        assert np.isfinite(J_analytic).all(), f"{map_entry.name}: non-finite Jacobian at {x}"
        np.testing.assert_allclose(
            J_analytic,
            J_fd,
            rtol=1e-4,
            atol=1e-6,
            err_msg=f"{map_entry.name}._jacobian disagrees with finite differences at {x}",
        )
        checked += 1

    assert checked >= _N_POINTS, (
        f"{map_entry.name}: only {checked} finite, smooth probes; need at least {_N_POINTS}"
    )


def test_overflowing_bogdanov_difference_stencil_is_not_a_jacobian_comparison():
    """A finite escaped state can give inf-inf, not evidence of a bad derivative."""
    import tsdynamics as ts

    system = ts.systems.Bogdanov()
    with np.errstate(all="raise"):
        assert (
            _smooth_fd_jacobian(
                type(system)._step, np.array([1e200, 1e200]), system.params.as_tuple()
            )
            is None
        )


def test_map_jacobian_checks_do_not_require_an_orbit_to_stay_bounded(monkeypatch):
    import tsdynamics as ts

    def escaping_run(*args, **kwargs):
        pytest.fail("Jacobian probes must not depend on an iterated orbit")

    monkeypatch.setattr(ts.systems.Bogdanov, "run", escaping_run)
    test_map_jacobian_matches_finite_differences(
        SimpleNamespace(cls=ts.systems.Bogdanov, name="Bogdanov")
    )


def test_one_wrong_jacobian_entry_cannot_be_outvoted(monkeypatch):
    import tsdynamics as ts

    cls = ts.systems.Bogdanov
    real = cls._jacobian
    affected = _map_probe_points(2, _N_POINTS)[0]

    def wrong(x, *params):
        result = np.array(real(x, *params))
        if np.array_equal(x, affected):
            result[0, 0] += 1.0
        return result

    monkeypatch.setattr(cls, "_jacobian", staticmethod(wrong))
    with pytest.raises(AssertionError, match="Bogdanov._jacobian disagrees"):
        test_map_jacobian_matches_finite_differences(SimpleNamespace(cls=cls, name="Bogdanov"))


@pytest.mark.parametrize("x", [0.0, _FD_H / 4.0])
def test_discontinuity_crossing_is_screened_independently_of_the_claimed_jacobian(x):
    def step(point):
        return np.where(point < 0.0, -1.0, 1.0)

    assert _smooth_fd_jacobian(step, np.array([x]), ()) is None
    np.testing.assert_array_equal(_smooth_fd_jacobian(step, np.array([0.5]), ()), [[0.0]])


