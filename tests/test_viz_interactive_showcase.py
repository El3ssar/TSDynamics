def test_threejs_example_fits_its_public_camera_and_has_no_honoring_gaps():
    from tsdynamics.viz.render.caps import style_honoring_gaps

    plot = showcase.build_plot("interactive-orbit")
    assert style_honoring_gaps(plot, "threejs") == []
    payload = plot.render("threejs", raw=True)
    camera = payload["metadata"]["camera"]
    target = np.asarray(camera["target"])
    position = np.asarray(camera["position"])
    delta = position - target
    assert np.rad2deg(np.arctan2(delta[1], delta[0])) == pytest.approx(-60)
    assert np.rad2deg(np.arctan2(delta[2], np.linalg.norm(delta[:2]))) == pytest.approx(24)
    bounds = payload["metadata"]["bounds"]
    diagonal = np.linalg.norm([value[1] - value[0] for value in bounds.values()])
    assert np.linalg.norm(delta) == pytest.approx(diagonal)


