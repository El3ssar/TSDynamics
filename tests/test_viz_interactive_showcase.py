class _Frames(HTMLParser):
    def __init__(self):
        super().__init__()
        self.frames = []

    def handle_starttag(self, tag, attrs):
        if tag == "iframe":
            self.frames.append(dict(attrs))


def test_live_examples_are_accessible_lazy_iframes_with_current_exports():
    parser = _Frames()
    parser.feed(showcase.PAGE.read_text())
    assert len(parser.frames) == 2
    for slug, frame in zip(showcase.EXAMPLES, parser.frames, strict=True):
        assert frame["src"].endswith(f"/{slug}.html")
        assert "tsd-live-viewer" in frame["class"]
        assert frame["loading"] == "lazy"
        assert len(frame["title"]) > 40
        assert int(frame["width"]) >= 900 and int(frame["height"]) >= 500
    assert showcase.validate_assets() == []


