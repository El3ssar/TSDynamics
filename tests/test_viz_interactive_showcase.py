def test_asset_guard_is_dependency_free_and_rejects_a_changed_asset(tmp_path, monkeypatch):
    script = r"""
import importlib.abc, sys
class NoExtras(importlib.abc.MetaPathFinder):
    def find_spec(self, fullname, path=None, target=None):
        if fullname.split('.')[0] in {'numpy', 'tsdynamics', 'matplotlib', 'plotly'}:
            raise ModuleNotFoundError(fullname)
sys.meta_path.insert(0, NoExtras())
sys.path.insert(0, 'docs/_tooling')
import make_interactive_showcase as showcase
assert showcase.validate_assets() == []
"""
    subprocess.run([sys.executable, "-c", script], cwd=showcase.ROOT, check=True, timeout=15)
    manifest = json.loads(showcase.MANIFEST.read_text())
    manifest["examples"]["interactive-trace"]["html_sha256"] = "stale"
    path = tmp_path / "showcase.json"
    path.write_text(json.dumps(manifest))
    monkeypatch.setattr(showcase, "MANIFEST", path)
    errors = showcase.validate_assets()
    assert len(errors) == 1 and "interactive-trace" in errors[0]
    assert showcase.REGENERATE in errors[0]


